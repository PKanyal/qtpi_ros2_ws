# shellcheck shell=bash
# ROS 2 networking for the buggy: CycloneDDS with unicast discovery.
#
# SOURCE this file (do not execute it). Used on BOTH the Pi and the laptop
# that runs RViz, so both sides use the same DDS setup.
#
# Why unicast: phone hotspots / campus Wi-Fi often drop multicast, so DDS
# discovery has to be pointed at explicit addresses ("peers").
#
# Peers written to the config (each side must list the OTHER machine):
#   * everything in $QTPI_PEERS (space-separated IPs or hostnames,
#     hostnames are resolved now; unresolvable ones are skipped),
#   * IPs listed one per line in ~/.config/qtpi/peers
#     (on the Pi, setup_laptop_rviz.sh adds the laptop's IP here),
#   * the IP of the SSH client, when this shell is an SSH session
#     (so anything started from the laptop's SSH session finds the laptop).
#
# Keep the list short: every address that has no machine behind it slows
# DDS discovery down (tested: 14 dead peers = no discovery in 10 s).
# Processes on the same machine find each other via local multicast.

_qtpi_ros_network() {
    local cfg_dir="${XDG_CONFIG_HOME:-$HOME/.config}/qtpi"
    local xml="$cfg_dir/cyclonedds.xml"
    local iface cidr

    mkdir -p "$cfg_dir" || return 1

    # Interface that carries the default route (wlan0 on the Pi).
    iface=$(ip -4 route show default 2>/dev/null | awk '{print $5; exit}')
    if [ -n "$iface" ]; then
        cidr=$(ip -4 -o addr show dev "$iface" scope global 2>/dev/null \
               | awk '{print $4; exit}')
    fi

    local names="${QTPI_PEERS:-}"
    if [ -f "$cfg_dir/peers" ]; then
        names="$names $(grep -v '^[[:space:]]*#' "$cfg_dir/peers" | tr '\n' ' ')"
    fi
    # IPv4 SSH clients only (this DDS setup is IPv4).
    case "${SSH_CLIENT%% *}" in
        *.*.*.*) names="$names ${SSH_CLIENT%% *}" ;;
    esac

    python3 - "$xml" "${iface:-}" "${cidr:-}" $names <<'PYEOF'
import ipaddress
import os
import socket
import sys

xml_path, iface, cidr = sys.argv[1], sys.argv[2], sys.argv[3]
extra = sys.argv[4:]

own = str(ipaddress.ip_interface(cidr).ip) if cidr else ""
peers = []

socket.setdefaulttimeout(3)
for name in extra:
    try:
        ip = socket.gethostbyname(name)
    except OSError:
        print(f"[ros_network] cannot resolve peer '{name}', skipping",
              file=sys.stderr)
        continue
    if ip.startswith("127.") or ip == own or ":" in ip:
        continue
    peers.append(ip)

seen = set()
peers = [p for p in peers if not (p in seen or seen.add(p))]

iface_xml = (f'<Interfaces><NetworkInterface name="{iface}"/></Interfaces>'
             if iface else "")
peer_xml = "\n".join(f'        <Peer address="{p}"/>' for p in peers)

xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/ros_network.sh - edits will be overwritten. -->
<CycloneDDS xmlns="https://cdds.io/config">
  <Domain Id="any">
    <General>
      {iface_xml}
      <!-- multicast only for discovery; still works locally even if the
           Wi-Fi drops multicast -->
      <AllowMulticast>spdp</AllowMulticast>
    </General>
    <Discovery>
      <ParticipantIndex>auto</ParticipantIndex>
      <!-- one index per ROS process; Nav2 + robot nodes need > 10 -->
      <MaxAutoParticipantIndex>40</MaxAutoParticipantIndex>
      <Peers>
{peer_xml}
      </Peers>
    </Discovery>
  </Domain>
</CycloneDDS>
"""

tmp = xml_path + ".tmp"
with open(tmp, "w") as f:
    f.write(xml)
os.replace(tmp, xml_path)
PYEOF
    [ $? -eq 0 ] || return 1

    export RMW_IMPLEMENTATION=rmw_cyclonedds_cpp
    export CYCLONEDDS_URI="file://$xml"
}

_qtpi_ros_network
unset -f _qtpi_ros_network
